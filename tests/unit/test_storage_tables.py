def _attachment_row(message_id, attachment_id):
    return {
        "message_id": message_id,
        "attachment_id": attachment_id,
        "url": f"https://cdn.example/{attachment_id}.png",
        "captured_at": "2026-11-11T00:00:00+00:00",
    }


def test_attachments_rejects_two_rows_with_the_same_message_and_attachment_id(tmp_path):
    engine = _sqlite_engine(tmp_path)
    with engine.begin() as connection:
        connection.execute(attachments.insert(), [_attachment_row(1, 10)])
    with pytest.raises(IntegrityError):
        with engine.begin() as connection:
            connection.execute(attachments.insert(), [_attachment_row(1, 10)])


def test_attachments_accepts_two_rows_with_different_attachment_ids(tmp_path):
    engine = _sqlite_engine(tmp_path)
    with engine.begin() as connection:
        connection.execute(
            attachments.insert(),
            [_attachment_row(1, 10), _attachment_row(1, 11)],
        )
        count = connection.execute(sa.select(sa.func.count()).select_from(attachments)).scalar_one()
    assert count == 2


def test_mysql_ddl_does_not_render_snowflake_primary_keys_as_auto_increment():
    """Snowflake keys are supplied by the application, never by the database.

    A MySQL ``AUTO_INCREMENT`` primary key would make the server allocate and
    burn a value on every insert, advancing the counter by ~10**18 per row.
    """
    for table_name, column_name in SNOWFLAKE_PRIMARY_KEYS.items():
        definition = _column_definition(
            metadata.tables[table_name], column_name, mysql.dialect()
        )
        assert not AUTO_INCREMENT.search(definition), (
            f"{table_name}.{column_name} must not be AUTO_INCREMENT on MySQL, "
            f"rendered as: {definition}"
        )


def test_mysql_ddl_still_renders_surrogate_primary_keys_as_auto_increment():
    """The surrogate ids are the only keys the database is allowed to generate."""
    for table_name, column_name in SURROGATE_PRIMARY_KEYS.items():
        definition = _column_definition(
            metadata.tables[table_name], column_name, mysql.dialect()
        )
        assert AUTO_INCREMENT.search(definition), (
            f"{table_name}.{column_name} must stay AUTO_INCREMENT on MySQL, "
            f"rendered as: {definition}"
        )


def test_snowflake_primary_keys_declare_autoincrement_false():
    for table_name, column_name in SNOWFLAKE_PRIMARY_KEYS.items():
        column = metadata.tables[table_name].c[column_name]
        assert column.autoincrement is False, (
            f"{table_name}.{column_name} must declare autoincrement=False, "
            f"got {column.autoincrement!r}"
        )


def test_surrogate_primary_keys_declare_autoincrement_true():
    for table_name, column_name in SURROGATE_PRIMARY_KEYS.items():
        column = metadata.tables[table_name].c[column_name]
        assert column.autoincrement is True, (
            f"{table_name}.{column_name} must declare autoincrement=True, "
            f"got {column.autoincrement!r}"
        )
